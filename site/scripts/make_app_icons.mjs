// Emits the Flutter app's launcher icons from the shared mark (scripts/mark.mjs),
// so the app and the site carry the identical bird.
//
//   icon.png             flag split + parrot   → iOS / legacy Android
//   icon_background.png  flag split alone      → Android adaptive back layer
//   icon_foreground.png  parrot on transparent → Android adaptive front layer
//
// ...and the website's favicon from the same two functions. That file used to
// be hand-written, and it drifted: the bird sat off-centre with its beak
// clipped by the right edge, which at 16px read as a smudge rather than a
// parrot. Generated here, the site and the app cannot disagree again.
//
// Android masks the adaptive foreground to a circle and can crop the outer ~18%
// on each side, so that layer draws the bird smaller — the lesson from the
// BullDozer icon, which lost its corners.
//
// sharp lives here in the site project, so run it from this directory:
//   node scripts/make_app_icons.mjs           (cwd: papagaio/site)
// then, in the app project: dart run flutter_launcher_icons
import sharp from 'sharp';
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { flagBack, parrot, svg } from '../../scripts/mark.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, '..', '..', '..', 'papagaio_app', 'assets', 'icon');
mkdirSync(OUT, { recursive: true });

const S = 1024;

const files = {
  'icon.png': svg(S, flagBack(S) + parrot(S, 0.62)),
  'icon_background.png': svg(S, flagBack(S)),
  // 0.46 keeps the bird inside the ~66% safe circle the launcher mask leaves.
  'icon_foreground.png': svg(S, parrot(S, 0.46)),
};

for (const [name, markup] of Object.entries(files)) {
  await sharp(Buffer.from(markup)).resize(S, S).png().toFile(join(OUT, name));
  console.log(`wrote ${name} (${S}px) → papagaio_app/assets/icon/`);
}

// --- the website ---------------------------------------------------------
// Same mark, same 0.62 share. The rounded clip is the one difference: iOS
// applies its own mask to a full-bleed square, a browser tab does not.
const WEB = join(__dirname, '..', 'public');
const rounded = (s, body) => svg(s,
  `<defs><clipPath id="r"><rect width="${s}" height="${s}" rx="${s * 0.22}"/></clipPath></defs>` +
  `<g clip-path="url(#r)">${body}</g>`);

const faviconMarkup = rounded(64, flagBack(64) + parrot(64, 0.62));
writeFileSync(join(WEB, 'icon.svg'),
  '<!-- Generated by site/scripts/make_app_icons.mjs from scripts/mark.mjs.\n' +
  '     Do not hand-edit: the app icon comes from the same two functions. -->\n' +
  faviconMarkup + '\n');
console.log('wrote icon.svg → site/public/');

// Safari and the iOS home screen ignore SVG favicons, so the raster fallbacks
// are not optional if the tab is to show a bird rather than a blank page.
for (const px of [32, 180]) {
  const name = px === 180 ? 'apple-touch-icon.png' : `icon-${px}.png`;
  await sharp(Buffer.from(rounded(S, flagBack(S) + parrot(S, 0.62))))
    .resize(px, px).png().toFile(join(WEB, name));
  console.log(`wrote ${name} (${px}px) → site/public/`);
}

// Home-screen icons for the manifest. Square, not rounded: Android applies its
// own mask, and a pre-rounded square inside a circular mask loses its corners
// twice. The bird is drawn smaller here for the same reason — a maskable icon
// can be cropped to the middle ~80%.
for (const px of [192, 512]) {
  await sharp(Buffer.from(svg(S, flagBack(S) + parrot(S, 0.5))))
    .resize(px, px).png().toFile(join(WEB, `icon-${px}.png`));
  console.log(`wrote icon-${px}.png (${px}px) → site/public/`);
}
