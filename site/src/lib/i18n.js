// Interface language for the site: English, European Portuguese or Russian.
//
// The same rule as the app (lib/data/l10n.dart): English is both the default
// and the key, so t('Verbs') returns 'Verbs' unless the interface speaks
// Portuguese or Russian, and an untranslated corner degrades to English rather
// than to a key name. Wording is copied from the app wherever the app already
// has the string, so the two read the same.
//
// The choice lives in localStorage 'pg_ui'. Without one, the browser's own
// language decides (ru → Russian, pt → Portuguese, anything else English).
// BaseLayout's inline head script repeats ui() in plain ES5 for the fetch
// wrapper and <html lang>; keep the two in step.

export const UI = ['en', 'pt', 'ru'];

export function ui() {
  try {
    const v = localStorage.getItem('pg_ui');
    if (UI.includes(v)) return v;
  } catch (e) { /* storage blocked: fall through to the browser language */ }
  const n = String((typeof navigator !== 'undefined' && navigator.language) || '').toLowerCase();
  if (n.startsWith('ru')) return 'ru';
  if (n.startsWith('pt')) return 'pt';
  return 'en';
}

export function setUi(v) {
  if (!UI.includes(v)) return;
  try { localStorage.setItem('pg_ui', v); } catch (e) { /* forgetful store */ }
}

// The RU or PT string for an English key; the key itself when missing.
export function t(en) {
  const u = ui();
  if (u === 'ru') return RU[en] ?? en;
  if (u === 'pt') return PT[en] ?? en;
  return en;
}

// A language named inside a sentence ("translate it into English"): lower
// case in Portuguese and Russian, which do not capitalise language names.
export function langName(code) {
  const n = t(code === 'en' ? 'English' : code === 'ru' ? 'Russian' : 'Portuguese');
  return ui() === 'en' ? n : n.toLowerCase();
}

