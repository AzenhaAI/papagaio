#!/usr/bin/env python3
"""Search keys: everyday phrases a resident types, pointing at the word Portugal uses.

    python3 scripts/build_search_keys.py <aliases.tsv> [<new_entries.json>]

aliases.tsv: pt headword<TAB>English phrases<TAB>Russian phrases ("; " separated).
new_entries.json: entries the dictionary lacked ([{t,p,g,e,ru,d}]); they are
appended to the app pack (layer rank 900000, like every lex: phrase row) and
written out as INSERT OR IGNORE SQL for D1.

A key is kept when it is a phrase, or a single word the search finds nothing
for today — a single word that already is some row's meaning ("iron", "stop")
stays with the ranking, or engomar would push ferro aside. Headwords match
exactly (Brazilian spellings like vôo and typos like saço are separate rows).

Writes: the app pack with a "k" list on keyed rows (../papagaio_app/assets/
packs/pt.json.gz), src/search_keys.js for the Worker, and
build/search_keys/new_entries.sql.
"""
import collections, gzip, json, re, sys, unicodedata

ROOT = __file__.rsplit('/scripts/', 1)[0]
PACK = ROOT + '/../papagaio_app/assets/packs/pt.json.gz'
fold = lambda s: ''.join(c for c in unicodedata.normalize('NFD', str(s).lower())
                         if unicodedata.category(c) != 'Mn').strip()

# The cards.fold column as scripts/parity_writeback.mjs writes it: "term trans".
dfold = lambda s: re.sub(r"['’`´ʼʹ]", '', fold(s))

pack = json.load(gzip.open(PACK))
aliases = [l.rstrip('\n').split('\t') for l in open(sys.argv[1], encoding='utf-8') if l.count('\t') == 2]
new = json.load(open(sys.argv[2], encoding='utf-8')) if len(sys.argv) > 2 else []

have = {(x['t'], x.get('p')) for x in pack}
added = []
for n in new:
    if (n['t'], n['p']) in have:
        continue
    pack.append({'t': n['t'], 'p': n['p'], 'g': n.get('g'), 'r': 900000,
                 'e': n['e'], 'ru': n['ru'], 'd': n['d']})
    have.add((n['t'], n['p']))
    added.append(n)

exact = collections.defaultdict(list)
low = collections.defaultdict(list)
for i, x in enumerate(pack):
    exact[x['t']].append(i)
    low[x['t'].lower()].append(i)
senses = set()
for x in pack:
    for part in (x.get('e') or '', x.get('ru') or ''):
        for s in re.split(r'[;,]', fold(re.sub(r'\([^)]*\)', '', part))):
            s = s.strip(' !?.«»"')
            if s:
                senses.add(s)
                if s.startswith('to '):
                    senses.add(s[3:])

keys = collections.defaultdict(set)
missing = []
for pt, en, ru in aliases:
    rows = exact.get(pt) or low.get(pt.lower())
    if not rows:
        missing.append(pt)
        continue
    rows = [r for r in rows if 'Brazil' not in (pack[r].get('e') or '')] or rows
    for k in [x.strip() for x in f'{en};{ru}'.split(';') if x.strip()]:
        fk = fold(k)
        if fk == 'first floor' or (' ' not in fk and fk in senses):
            continue
        # One headword, several rows (gelado the adjective and the ice cream):
        # the key goes to the rows whose gloss shares a word with it. When
        # none does and the headword has several rows, the key is dropped as
        # ambiguous — attached to all of them, "good luck" opened força the
        # noun, "force".
        words = set(re.findall(r'\w{3,}', fk))
        share = [r for r in rows if words & set(re.findall(r'\w{3,}', fold(f"{pack[r].get('e') or ''} {pack[r].get('ru') or ''}")))]
        for r in share or (rows if len(rows) == 1 else []):
            keys[r].add(k)

for x in pack:
    x.pop('k', None)
for r, ks in keys.items():
    pack[r]['k'] = sorted(ks)
open(PACK, 'wb').write(gzip.compress(json.dumps(pack, ensure_ascii=False, separators=(',', ':')).encode()))

# Worker map: phrase -> candidate D1 ids (lex: or lexpt:, whichever exists).
by_key = collections.defaultdict(list)
for r, ks in keys.items():
    x = pack[r]
    for k in ks:
        for layer in ('lex', 'lexpt'):
            i = f"{layer}:{x['t']}|{x['p']}"
            if i not in by_key[k]:
                by_key[k].append(i)
js = ('// Generated by scripts/build_search_keys.py — do not edit by hand.\n'
      '// Everyday phrases a resident types, mapped to the dictionary rows Portugal uses.\n'
      "import { fold } from './verbs.js';\n\n"
      f'export const SEARCH_KEYS = {json.dumps(dict(sorted(by_key.items())), ensure_ascii=False)};\n\n'
      'let folded;\n'
      '/** Folded phrase -> D1 ids, built on first use. */\n'
      'export function searchKeys() {\n'
      '  if (!folded) {\n'
      '    folded = new Map();\n'
      '    for (const [k, ids] of Object.entries(SEARCH_KEYS)) {\n'
      '      const f = fold(k);\n'
      '      folded.set(f, [...new Set([...(folded.get(f) ?? []), ...ids])]);\n'
      '    }\n'
      '  }\n'
      '  return folded;\n'
      '}\n')
open(ROOT + '/src/search_keys.js', 'w', encoding='utf-8').write(js)

q = lambda v: 'NULL' if v is None else "'" + str(v).replace("'", "''") + "'"
sql = [f"INSERT OR IGNORE INTO cards (id, course, term, trans, pos, gender, tags, freq, owner, fold, trans_ru, def_pt, trans_en) VALUES ("
       + ', '.join([q(f"lex:{n['t']}|{n['p']}"), q('pt'), q(n['t']), q(n['e']), q(n['p']), q(n.get('g')),
                    q('["lexicon","resident"]'), '900000', q('lex'), q(f"{dfold(n['t'])} {dfold(n['e'])}"), q(n['ru']), q(n['d']), q(n['e'])]) + ');'
       for n in added]
open(ROOT + '/build/search_keys/new_entries.sql', 'w', encoding='utf-8').write('\n'.join(sql) + '\n')
print(f'pack: {len(added)} entries added, {len(keys)} rows keyed ({sum(map(len, keys.values()))} keys); '
      f'worker: {len(by_key)} phrases; still missing: {len(missing)} {missing[:10]}')
