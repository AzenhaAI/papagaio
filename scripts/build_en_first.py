#!/usr/bin/env python3
"""English word -> the Portuguese word whose first meaning it is, for /api/search.

    python3 scripts/build_en_first.py [path/to/pt.json.gz]

Why: the worker's fast path is a prefix scan on the folded headword, so an
English query that happens to begin a Portuguese word lost to it: "iron"
listed ironia, irónico, ironicamente — ferro never appeared, while the app,
which ranks meanings too, put ferro first. This map gives the worker the same
answer without the 140k-row gloss scan: for every English first sense of a
ranked word (frequency rank <= 30000, not Brazilian), the two most frequent
Portuguese rows. The worker uses it only when no Portuguese headword is
spelled exactly like the query, so "casa", "real" or "sol" are untouched.

Writes src/en_first.js.
"""
import gzip, json, re, sys, unicodedata
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACK = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / 'Projects/papagaio_app/assets/packs/pt.json.gz'

def fold(s):
    s = unicodedata.normalize('NFD', s.lower())
    return re.sub(r"[̀-ͯ]", '', s).replace("'", '').replace('’', '').strip()

def sense1(e):
    first = re.split(r'[;,]', e or '')[0]
    if re.search(r'\((brazil|br\b|archaic|obsolete|slang)', first, re.I):
        return None
    first = re.sub(r'\([^)]*\)', '', first)
    first = re.sub(r'^(to|a|an|the) ', '', first.strip().lower()).strip()
    if not first or len(first) < 2 or len(first.split()) > 2 or not re.fullmatch(r"[a-z][a-z' -]*", first):
        return None
    return fold(first)

rows = json.load(gzip.open(PACK))
best = defaultdict(list)
for r in rows:
    rank = r.get('r') or 10**9
    if rank > 30000 or r.get('e', '').startswith('('):
        continue
    k = sense1(r.get('e'))
    if k:
        if fold(r['t']) != k:  # an anglicism spelled like the query is no translation of it
            best[k].append((rank, r['p'] != 'noun', r['t'], r['p']))
out = {}
for k, cands in best.items():
    cands.sort()
    ids = []
    for rank, _, t, p in cands[:2]:
        ids += [f'lex:{t}|{p}', f'lexpt:{t}|{p}']
    out[k] = ids
dest = ROOT / 'src/en_first.js'
dest.write_text(
    '// Generated by scripts/build_en_first.py — do not edit by hand.\n'
    '// English first sense -> D1 ids of the Portuguese words it translates.\n'
    'export const EN_FIRST = ' + json.dumps(dict(sorted(out.items())), ensure_ascii=False) + ';\n'
    'let map = null;\n'
    'export const enFirst = () => (map ??= new Map(Object.entries(EN_FIRST)));\n')
print(f'{len(out)} English words -> {dest} ({dest.stat().st_size // 1024} KB)')
for w in ('iron', 'dog', 'house', 'go', 'bus', 'key', 'bread', 'pharmacy', 'cheese'):
    print(' ', w, out.get(w, [])[:4:2])
