// Builds the CEFR level tags (A1-A2 / B1 / B2) from the vocabulary lists of a
// course book series the owner studies from.
//
// Only the tag travels: word → level. The lists themselves (with units and
// pages) stay in build/aprender/, which is not committed — the books are
// copyrighted, and a level on a word is a fact about the word, not their text.
//
//   node scripts/build_levels.mjs
//
// Reads build/aprender/aprender_vocab.json ([{level, unit, book_page, pt, ru}]).
// Writes src/levels.js (the worker: lookups, the site, the bot) and
// ../papagaio_app/assets/packs/levels.json (the app, offline).

import { readFileSync, writeFileSync } from 'node:fs';

const RANK = { 'A1-A2': 0, B1: 1, B2: 2 };
const fold = (s) => String(s ?? '').toLowerCase().normalize('NFD')
  .replace(/[̀-ͯ]/g, '').trim();

// "o médico / a médica", "casado/a", "povoado – habitado, populoso",
// "preencher – ocupar (um cargo)" → the headwords they name.
function headwords(pt) {
  const head = String(pt).split(/\s[–—-]\s/)[0].replace(/\(.*?\)/g, ' ');
  const out = [];
  for (let part of head.split(/\s*\/\s*|,\s*/)) {
    part = part.trim().replace(/^(o|a|os|as|um|uma)\s+/i, '').replace(/[.;:!?]+$/, '').trim();
    if (!part) continue;
    out.push(part);
  }
  // "casado/a": the second half is an ending, not a word.
  if (/^[a-zà-ü]+\/[ao]s?$/i.test(head.trim())) {
    const [stem, end] = head.trim().split('/');
    return [stem, stem.replace(/[ao]s?$/i, '') + end];
  }
  return out.filter((w) => w.length > 1 && w.split(' ').length <= 4);
}

const src = JSON.parse(readFileSync('build/aprender/aprender_vocab.json', 'utf8'));
const levels = {};
for (const row of src) {
  if (!(row.level in RANK)) continue;
  for (const w of headwords(row.pt)) {
    const k = fold(w);
    if (!(k in levels) || RANK[row.level] < RANK[levels[k]]) levels[k] = row.level;
  }
}

const count = (l) => Object.values(levels).filter((x) => x === l).length;
writeFileSync('src/levels.js',
  '// Generated by scripts/build_levels.mjs — do not edit.\n' +
  '// CEFR level per folded headword (A1-A2 / B1 / B2).\n' +
  `export const LEVELS = ${JSON.stringify(levels)};\n`);
writeFileSync('../papagaio_app/assets/packs/levels.json', JSON.stringify(levels));
console.log(`${Object.keys(levels).length} words: A1-A2 ${count('A1-A2')}, B1 ${count('B1')}, B2 ${count('B2')}`);
