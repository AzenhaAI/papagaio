// Builds the Madeirense dictionary from the edited chunks.
//
// Source: "Vocabulário Popular da Madeira", P.e Fernando Augusto da Silva,
// Junta Geral do Funchal, 1950 (the author died in 1949; the text is in the
// public domain). The definitions are the author's, verbatim; the modern
// spelling, the English and Russian meanings and the links to the standard
// dictionary are ours.
//
//   node scripts/build_madeira.mjs [--draft]
//
// Reads build/madeira/chunks/out_N.json (the edited entries). With --draft,
// or while a chunk is still missing, the raw in_N.json stands in so the
// screens can be built before the edit is done; a draft is never shipped.
//
// Writes:
//   data/madeira/madeira.json                      the full dictionary (repo)
//   ../papagaio_app/assets/packs/madeira.json      compact, for the app (plain:
//                                                  store packages compress it,
//                                                  and the web build has no gzip)
//   src/madeira.js                                 term index for the worker

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { gzipSync } from 'node:zlib';

const draftOnly = process.argv.includes('--draft');
const CHUNKS = 4;
const dir = 'build/madeira/chunks';

const fold = (s) => String(s ?? '').toLowerCase().normalize('NFD')
  .replace(/[̀-ͯ]/g, '').trim();

// A raw entry in the edited shape, for drafts only: lowercase headword
// without its parenthetical note, the 1950 definition as is.
const fromRaw = (x) => ({
  id: x.id,
  term_1950: x.term,
  term: x.term.replace(/\s*\(.*?\)\s*/g, ' ').trim().toLowerCase(),
  form_note: (x.term.match(/\((.*?)\)/) ?? [])[1] ?? '',
  pos: '',
  definition_pt: x.definition_pt,
  definition_pt_modern: x.definition_pt,
  en: x.en,
  ru: x.ru,
  standard: null,
  domain: '',
  confidence: 'draft',
  flag: '',
});

let entries = [];
let drafted = 0;
for (let n = 1; n <= CHUNKS; n++) {
  const out = `${dir}/out_${n}.json`;
  if (!draftOnly && existsSync(out)) {
    entries.push(...JSON.parse(readFileSync(out, 'utf8')));
  } else {
    const raw = JSON.parse(readFileSync(`${dir}/in_${n}.json`, 'utf8'));
    entries.push(...raw.map(fromRaw));
    drafted += raw.length;
  }
}
entries.sort((a, b) => fold(a.term).localeCompare(fold(b.term), 'pt'));

const missing = entries.filter((e) => !e.term || !e.en || !e.ru);
if (missing.length) {
  console.error(`${missing.length} entries lack term/en/ru, e.g. id ${missing[0].id}`);
  process.exit(1);
}

const source = {
  title: 'Vocabulário Popular da Madeira',
  author: 'P.e Fernando Augusto da Silva',
  publisher: 'Junta Geral do Funchal',
  year: 1950,
};

writeFileSync('data/madeira/madeira.json',
  JSON.stringify({ source, draft: drafted > 0, entries }, null, 1) + '\n');

// The app's copy: short keys, empty fields dropped.
const compact = entries.map((e) => {
  const c = {
    i: e.id, t: e.term, t0: e.term_1950, p: e.pos, d: e.definition_pt_modern,
    d0: e.definition_pt, e: e.en, ru: e.ru, n: e.form_note, dom: e.domain,
    // Low confidence: shown with "meaning not established", not hidden.
    lo: e.confidence === 'low' ? 1 : null,
  };
  if (e.standard?.lemma) {
    c.s = e.standard.lemma;
    c.r = e.standard.relation;
    c.se = e.standard.standard_en;
  }
  for (const k of Object.keys(c)) if (c[k] === '' || c[k] == null) delete c[k];
  return c;
});
const app = '../papagaio_app/assets/packs/madeira.json';
writeFileSync(app, JSON.stringify({ source, entries: compact }));

// The worker only needs to know which words have a Madeiran sense, and what
// it is, to add it to a lookup; the folded term (modern and 1950 spellings,
// and the standard lemma it is linked to) is the key.
const index = {};
const add = (k, c) => { if (k) (index[fold(k)] ??= []).some((x) => x.i === c.i) || index[fold(k)].push(c); };
for (const c of compact) { add(c.t, c); add(c.t0?.replace(/\s*\(.*?\)\s*/g, ' '), c); add(c.s, c); }
writeFileSync('src/madeira.js',
  '// Generated by scripts/build_madeira.mjs from data/madeira/madeira.json — do not edit.\n' +
  `// ${source.title}, ${source.author}, ${source.year}.\n` +
  `export const MADEIRA_SOURCE = ${JSON.stringify(source)};\n` +
  `export const MADEIRA = ${JSON.stringify(index)};\n`);

console.log(`${entries.length} entries (${drafted} draft), ` +
  `${compact.filter((c) => c.s).length} linked to the standard dictionary; ` +
  `app pack ${(gzipSync(JSON.stringify(compact)).length / 1024).toFixed(0)} KB gz`);
